/**
 * Emit the product identity for artifacts that cannot import TypeScript.
 *
 * The compiled hook relay (C), the shell relays, and the CommonJS test
 * preload all need the namespace, but none of them can `import` from
 * waykeep-contract. Before this generator they each spelled the values by
 * hand, which meant the "rename is one line" property was false for exactly
 * the artifacts whose staleness fails silently — a relay pointed at a
 * directory nobody writes, or a test harness that stops redirecting and
 * operates on the developer's real home.
 *
 * Run after `tsc -b` (it reads the COMPILED contract, so there is one source
 * of truth rather than a parallel parse of the TypeScript).
 *
 * Emits into dist/generated/:
 *   identity.h     C  #defines, included by hook-relay.c
 *   identity.sh    sh variables, sourced by the shell relays
 *   identity.json  read by the .cjs/.mjs harnesses
 */
import { mkdirSync, writeFileSync, copyFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(REPO, 'dist', 'generated');

const { NAMESPACE, DATA_DIR_NAME, DB_FILENAME, ENV_PREFIX, MCP_SERVER_NAME,
        RELAY_PROBE_FLAG, RELAY_PROBE_SENTINEL } =
  await import(join(REPO, 'packages', 'contract', 'dist', 'identity.js'));
const { CLIENT_HEADER, CLIENT_ENV_VAR } =
  await import(join(REPO, 'packages', 'contract', 'dist', 'clients.js'));
const { ENV } = await import(join(REPO, 'dist', 'src', 'constants', 'env.js'));
const { FILES } = await import(join(REPO, 'dist', 'src', 'constants', 'paths.js'));

/** Everything a non-TypeScript artifact may need, in one flat table. */
const IDENTITY = {
  NAMESPACE,
  DATA_DIR: DATA_DIR_NAME,
  DB_FILE: DB_FILENAME,
  ENV_PREFIX,
  MCP_SERVER_NAME,
  SOCKET_FILE: FILES.SOCKET,
  PID_FILE: FILES.PID,
  FALLBACK_LOG_FILE: FILES.RELAY_FALLBACK_LOG,
  CONFIG_FILE: FILES.CONFIG,
  CLIENT_STATE_FILE: FILES.CLIENT_STATE,
  CLIENT_HEADER,
  /** Relay self-identification handshake — defined by the contract, not here. */
  PROBE_FLAG: RELAY_PROBE_FLAG,
  PROBE_SENTINEL: RELAY_PROBE_SENTINEL,
  /** mktemp template prefix for the shell relay's spool file. */
  TMP_PREFIX: `${NAMESPACE}-hook`,
  ENV: { ...ENV, CLIENT: CLIENT_ENV_VAR },
};

const BANNER_LINES = [
  'GENERATED by scripts/gen-identity.mjs — DO NOT EDIT.',
  'Source of truth: packages/contract/src/identity.ts (NAMESPACE).',
  'Regenerate with: npm run build:identity',
];
/** Line-comment banner (shell, and anything else using a line prefix). */
const banner = (prefix) => BANNER_LINES.map(l => `${prefix} ${l}`).join('\n') + '\n';
/** A single, properly closed C block comment — three `/*` opens would swallow the file. */
const cBanner = () => ['/*', ...BANNER_LINES.map(l => ` * ${l}`), ' */'].join('\n');

const cEscape = (s) => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"');

// --- C header --------------------------------------------------------------
const hLines = [
  cBanner(),
  '',
  '#ifndef WAYKEEP_IDENTITY_H',
  '#define WAYKEEP_IDENTITY_H',
  '',
  `#define WK_DATA_DIR "${cEscape(IDENTITY.DATA_DIR)}"`,
  `#define WK_SOCKET_FILE "${cEscape(IDENTITY.SOCKET_FILE)}"`,
  `#define WK_FALLBACK_LOG_FILE "${cEscape(IDENTITY.FALLBACK_LOG_FILE)}"`,
  `#define WK_CLIENT_HEADER "${cEscape(IDENTITY.CLIENT_HEADER)}"`,
  `#define WK_PROBE_FLAG "${cEscape(IDENTITY.PROBE_FLAG)}"`,
  `#define WK_PROBE_SENTINEL "${cEscape(IDENTITY.PROBE_SENTINEL)}"`,
  `#define WK_ENV_CLIENT "${cEscape(IDENTITY.ENV.CLIENT)}"`,
  `#define WK_ENV_NODE "${cEscape(IDENTITY.ENV.NODE)}"`,
  `#define WK_ENV_GOVERNANCE_TIMEOUT_MS "${cEscape(IDENTITY.ENV.GOVERNANCE_TIMEOUT_MS)}"`,
  `#define WK_ENV_DAEMON_TIMEOUT_MS "${cEscape(IDENTITY.ENV.DAEMON_TIMEOUT_MS)}"`,
  '',
  '/* Built by literal concatenation so the pieces stay independently named. */',
  '#define WK_SOCK_PATH_TEMPLATE "%s/" WK_DATA_DIR "/" WK_SOCKET_FILE',
  '#define WK_FALLBACK_LOG_TEMPLATE "%s/" WK_DATA_DIR "/" WK_FALLBACK_LOG_FILE',
  '',
  '#endif /* WAYKEEP_IDENTITY_H */',
  '',
].join('\n');

// --- shell fragment --------------------------------------------------------
const shEscape = (s) => String(s).replace(/'/g, `'\\''`);
const shLines = [
  banner('#'),
  `WK_NAMESPACE='${shEscape(IDENTITY.NAMESPACE)}'`,
  `WK_DATA_DIR='${shEscape(IDENTITY.DATA_DIR)}'`,
  `WK_SOCKET_FILE='${shEscape(IDENTITY.SOCKET_FILE)}'`,
  `WK_CLIENT_HEADER='${shEscape(IDENTITY.CLIENT_HEADER)}'`,
  `WK_ENV_CLIENT='${shEscape(IDENTITY.ENV.CLIENT)}'`,
  `WK_TMP_PREFIX='${shEscape(IDENTITY.TMP_PREFIX)}'`,
  `WK_PROBE_FLAG='${shEscape(IDENTITY.PROBE_FLAG)}'`,
  `WK_PROBE_SENTINEL='${shEscape(IDENTITY.PROBE_SENTINEL)}'`,
  '',
].join('\n');

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, 'identity.h'), hLines);
writeFileSync(join(OUT_DIR, 'identity.sh'), shLines);
writeFileSync(join(OUT_DIR, 'identity.json'), JSON.stringify(IDENTITY, null, 2) + '\n');

// The shell relays source this from their OWN directory, so it ships beside them.
const hooksDist = join(REPO, 'dist', 'src', 'hooks');
mkdirSync(hooksDist, { recursive: true });
copyFileSync(join(OUT_DIR, 'identity.sh'), join(hooksDist, 'identity.sh'));

console.log(`gen-identity: namespace="${NAMESPACE}" -> dist/generated/{identity.h,identity.sh,identity.json}`);
